"""Bootstrap 95% confidence intervals for the deployed system's test metrics.

The Hindi (26 messages) and Hinglish (94 messages) test sets are small, so a
single number such as "20% false alarms" hides a lot of uncertainty. This
script resamples the test set many times (with replacement) and reports the
range in which the middle 95% of results fall.

Needs the processed splits from ``python -m training.prepare_data`` and the
trained model in ``models/``. Writes ``reports/BOOTSTRAP_CI.md``.

    python -m training.bootstrap_ci            # 2000 resamples (default)
    python -m training.bootstrap_ci --n 500    # faster
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

import numpy as np
import pandas as pd

from scam_detector.detector import score_texts
from scam_detector.model import thresholds

ROOT = Path(__file__).resolve().parent.parent
TEST = ROOT / "data" / "processed" / "test.csv"
OUT_MD = ROOT / "reports" / "BOOTSTRAP_CI.md"
OUT_JSON = ROOT / "reports" / "bootstrap_ci.json"


def rates(y: np.ndarray, flag: np.ndarray) -> dict:
    tp = int(((y == 1) & flag).sum())
    fp = int(((y == 0) & flag).sum())
    fn = int(((y == 1) & ~flag).sum())
    tn = int(((y == 0) & ~flag).sum())
    return {
        "recall": tp / (tp + fn) if tp + fn else np.nan,
        "fpr": fp / (fp + tn) if fp + tn else np.nan,
        "precision": tp / (tp + fp) if tp + fp else np.nan,
    }


def bootstrap(y: np.ndarray, flag: np.ndarray, n: int, rng: np.random.Generator) -> dict:
    point = rates(y, flag)
    samples = {k: [] for k in point}
    for _ in range(n):
        idx = rng.integers(0, len(y), len(y))
        r = rates(y[idx], flag[idx])
        for k, v in r.items():
            samples[k].append(v)
    out = {}
    for k, v in point.items():
        arr = np.array(samples[k], dtype=float)
        arr = arr[~np.isnan(arr)]
        lo, hi = (np.percentile(arr, [2.5, 97.5]) if len(arr) else (np.nan, np.nan))
        out[k] = {"value": round(float(v), 3), "ci_low": round(float(lo), 3), "ci_high": round(float(hi), 3)}
    return out


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=2000, help="number of bootstrap resamples")
    ap.add_argument("--seed", type=int, default=42)
    args = ap.parse_args()

    if not TEST.exists():
        raise SystemExit("No test split found. Run:  python -m training.prepare_data")
    df = pd.read_csv(TEST)
    y = df["label"].to_numpy().astype(int)
    risk = np.array([r["risk"] for r in score_texts(df["text"].astype(str).tolist())])
    flag = risk >= thresholds()["suspicious"]  # SUSPICIOUS or SCAM counts as "flagged"

    rng = np.random.default_rng(args.seed)
    groups = {"all": np.ones(len(df), dtype=bool)}
    for lang in ("en", "hinglish", "hi"):
        groups[lang] = (df["language"] == lang).to_numpy()

    results = {}
    for name, mask in groups.items():
        results[name] = {
            "n": int(mask.sum()),
            "scams": int(y[mask].sum()),
            **bootstrap(y[mask], flag[mask], args.n, rng),
        }

    OUT_JSON.write_text(json.dumps({"resamples": args.n, "seed": args.seed, "groups": results}, indent=2))

    def cell(m: dict) -> str:
        return f"{m['value']:.3f} ({m['ci_low']:.3f} to {m['ci_high']:.3f})"

    lines = [
        "# Bootstrap 95% confidence intervals (auto-generated by `python -m training.bootstrap_ci`)",
        "",
        f"Deployed system (TF-IDF + LogReg + rules), test split, flagged = SUSPICIOUS or SCAM. "
        f"{args.n} resamples with replacement, seed {args.seed}. Each cell: value (95% CI).",
        "",
        "Same caveat as `RESULTS.md`: public + synthetic data only, not real messages to Indian users.",
        "",
        "| group | n | scams | recall | FPR (false alarms) | precision |",
        "|:--|--:|--:|:--|:--|:--|",
    ]
    for name, r in results.items():
        lines.append(f"| {name} | {r['n']} | {r['scams']} | {cell(r['recall'])} | {cell(r['fpr'])} | {cell(r['precision'])} |")
    lines.append("")
    OUT_MD.write_text("\n".join(lines), encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
